"""Fuzz adbwire with hostile peers: every outcome is a value or a TransportError, never a hang.

A peer is a `ScriptedSocket` that plays back generated bytes in random chunks and then closes,
goes silent (a socket timeout) or resets. The properties, for each exchange:

- the result is a value or a `TransportError` subclass (no other exception type escapes);
- the peer never has to be waited on (the fake raises `TimeoutError` instead of blocking, which
  is what a socket with a timeout does);
- the code never reads past what the peer announced: it asks the socket for no more than the
  remaining length, never for a body whose length was malformed or above the cap, and so the
  bytes it consumed never exceed `bound(...)`, computed here from the generated bytes alone.

`max_examples` is pinned at 500 or the active profile's count if that is higher, so the `ci`
profile (200 by default) still gives at least 500 examples for each test; `test_fuzz_budget`
checks that.
"""

import re

from hypothesis import given, settings
from hypothesis import strategies as st

from sift.device import adbwire
from sift.device.transport import TransportError
from tests.device.fake_socket import ScriptedSocket, as_socket

MIN_EXAMPLES = 500
FUZZ = settings(max_examples=max(MIN_EXAMPLES, settings().max_examples), deadline=None)
CAP = 64

_HEX4 = re.compile(rb"[0-9a-fA-F]{4}")

ends = st.sampled_from(["eof", "stall", "reset"])
chunks = st.integers(min_value=1, max_value=9)


@st.composite
def peer_bytes(draw: st.DrawFn) -> bytes:
    """A reply to a host request, from well formed to garbage."""
    body = draw(st.binary(max_size=2 * CAP))
    kind = draw(
        st.sampled_from(
            [
                "random",
                "okay_string",
                "fail_string",
                "truncated_status",
                "bad_hex_length",
                "negative_length",
                "over_cap",
                "zero_length",
                "cut_mid_length",
                "cut_mid_body",
            ]
        )
    )
    exact = b"%04x" % len(body)
    if kind == "random":
        return draw(st.binary(max_size=3 * CAP))
    if kind == "okay_string":
        return b"OKAY" + exact + body
    if kind == "fail_string":
        return b"FAIL" + exact + body
    if kind == "truncated_status":
        status = draw(st.sampled_from([b"OKAY", b"FAIL"]))
        return status[: draw(st.integers(min_value=0, max_value=3))]
    if kind == "bad_hex_length":
        bad = draw(st.binary(min_size=4, max_size=4).filter(lambda b: not _HEX4.fullmatch(b)))
        return draw(st.sampled_from([b"OKAY", b"FAIL"])) + bad + body
    if kind == "negative_length":
        texts = [b"-001", b"-0ff", b"+004", b" 004", b"0x04", b"0_04", b"-1  "]
        text = draw(st.sampled_from(texts))
        return b"OKAY" + text[:4] + body
    if kind == "over_cap":
        length = draw(st.integers(min_value=CAP + 1, max_value=0xFFFF))
        return b"OKAY" + b"%04x" % length + body
    if kind == "zero_length":
        return b"OKAY0000" + draw(st.binary(max_size=8))
    if kind == "cut_mid_length":
        return b"OKAY" + exact[: draw(st.integers(min_value=0, max_value=3))]
    # cut_mid_body
    return b"OKAY" + exact + body[: draw(st.integers(min_value=0, max_value=max(len(body) - 1, 0)))]


def bound(data: bytes, cap: int) -> int:
    """The most bytes a correct reader may consume from `data` (status, length, string)."""
    if data[:4] not in (b"OKAY", b"FAIL"):
        return 4
    header = data[4:8]
    if not _HEX4.fullmatch(header):
        return 4 + min(len(header), 4)
    length = int(header, 16)
    limit = min(cap, adbwire.MAX_FAIL_TEXT) if data[:4] == b"FAIL" else cap
    return 8 if length > limit else 8 + length


@FUZZ
@given(data=peer_bytes(), chunk=chunks, end=ends)
def test_host_request_then_string_never_misbehaves(data: bytes, chunk: int, end: str) -> None:
    fake = ScriptedSocket(data, chunk=chunk, end=end)  # type: ignore[arg-type]
    try:
        adbwire.host_request(as_socket(fake), b"host:version", max_bytes=100)
        outcome: object = adbwire.read_host_string(as_socket(fake), max_bytes=CAP)
    except TransportError as e:
        outcome = e
    assert isinstance(outcome, str | TransportError)
    assert fake.delivered <= bound(data, CAP)
    assert fake.largest_request <= 4 + CAP  # never more than a status, or a capped body
    if isinstance(outcome, str):
        # A value means the peer really sent OKAY, a well formed length and the whole string.
        assert data[:4] == b"OKAY"
        assert fake.delivered == 8 + len(outcome.encode()) or "�" in outcome


@FUZZ
@given(data=st.binary(max_size=3 * CAP), chunk=chunks, end=ends, cap=st.integers(0, 2 * CAP))
def test_read_hex_length_never_misbehaves(data: bytes, chunk: int, end: str, cap: int) -> None:
    fake = ScriptedSocket(data, chunk=chunk, end=end)  # type: ignore[arg-type]
    try:
        outcome: object = adbwire.read_hex_length(as_socket(fake), max_bytes=cap)
    except TransportError as e:
        outcome = e
    assert isinstance(outcome, int | TransportError)
    assert fake.delivered <= 4
    if isinstance(outcome, int):
        assert 0 <= outcome <= cap
        assert _HEX4.fullmatch(data[:4])


@FUZZ
@given(raw=st.binary(max_size=8))
def test_parse_hex_length_matches_a_strict_reading(raw: bytes) -> None:
    try:
        value: int | None = adbwire.parse_hex_length(raw)
    except TransportError:
        value = None
    if _HEX4.fullmatch(raw):
        assert value == int(raw.decode("ascii"), 16)
    else:
        assert value is None


@FUZZ
@given(
    serial=st.text(max_size=20),
    data=peer_bytes(),
    second=peer_bytes(),
    chunk=chunks,
    end=ends,
)
def test_open_service_replies_never_misbehave(
    serial: str, data: bytes, second: bytes, chunk: int, end: str
) -> None:
    """Both replies of `open_service` (transport, then service) are fuzzed as one stream."""
    fake = ScriptedSocket(data + second, chunk=chunk, end=end)  # type: ignore[arg-type]
    try:
        adbwire.host_request(as_socket(fake), b"host:transport:" + serial.encode())
        adbwire.host_request(as_socket(fake), b"sync:")
    except TransportError:
        pass
    assert fake.delivered <= len(data) + len(second)
    assert fake.largest_request <= adbwire.MAX_FAIL_TEXT + 4


def test_fuzz_budget() -> None:
    """Each fuzz test runs at least 500 examples under any profile (dev 50, ci 200)."""
    for test in (
        test_host_request_then_string_never_misbehaves,
        test_read_hex_length_never_misbehaves,
        test_parse_hex_length_matches_a_strict_reading,
        test_open_service_replies_never_misbehave,
    ):
        assert test._hypothesis_internal_use_settings.max_examples >= MIN_EXAMPLES  # type: ignore[attr-defined]
