"""Print a compact map of the Python and web sources: one line per module, its public names.

Run `make codemap` to refresh docs/CODEMAP.md. Reading that file is much cheaper than opening
modules one by one to find where something lives.
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def first_line(doc: str | None) -> str:
    return (doc or "").strip().splitlines()[0].rstrip(".") if doc and doc.strip() else ""


def py_module(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            methods = [
                n.name
                for n in node.body
                if isinstance(n, ast.FunctionDef | ast.AsyncFunctionDef)
                and not n.name.startswith("_")
            ]
            names.append(f"{node.name}({', '.join(methods)})" if methods else node.name)
        elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and not node.name.startswith(
            "_"
        ):
            names.append(f"{node.name}()")
    rel = path.relative_to(ROOT / "src")
    head = f"- `{rel}`"
    doc = first_line(ast.get_docstring(tree))
    lines = [f"{head}: {doc}" if doc else head]
    if names:
        lines.append(f"  - {'; '.join(names)}")
    return lines


EXPORT = re.compile(
    r"^export (?:default )?(?:async )?(?:function|const|class|type|interface) (\w+)", re.M
)


def web_module(path: Path) -> list[str]:
    names = EXPORT.findall(path.read_text(encoding="utf-8"))
    rel = path.relative_to(ROOT)
    return [f"- `{rel}`: {', '.join(names)}" if names else f"- `{rel}`"]


def main() -> None:
    out = [
        "# Code map",
        "",
        "Generated by `make codemap` (scripts/codemap.py). Do not edit by hand.",
        "",
    ]
    out.append("## Python (`src/`)")
    out.append("")
    for path in sorted((ROOT / "src").rglob("*.py")):
        if path.name == "__init__.py" and path.stat().st_size < 200:
            continue
        out.extend(py_module(path))
    migrations = sorted(p.name for p in (ROOT / "src").rglob("migrations/*.sql"))
    out += ["", "Migrations: " + ", ".join(migrations), "", "## Web (`web/src/`)", ""]
    for path in sorted((ROOT / "web" / "src").rglob("*.ts*")):
        if ".test." in path.name or path.name.endswith(".d.ts"):
            continue
        out.extend(web_module(path))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
